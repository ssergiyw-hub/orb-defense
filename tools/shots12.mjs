// Jeweler autosearch + synthesis, energy flask, rune rarity, shop chests, hero menus.
import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 800 }, deviceScaleFactor: 2, hasTouch: true });
const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
const shot = n => p.screenshot({ path: `shots/y-${n}.png` });
const click = sel => p.evaluate(s => document.querySelector(s)?.click(), sel);
await p.goto('file://' + process.cwd() + '/dist/index.html');
await click('[data-a="startPick"][data-v="poseidon"]'); await click('[data-a="startGo"]'); await p.waitForTimeout(300);
await p.evaluate(() => { const s = JSON.parse(localStorage.getItem('mw-profile-v1')); s.gold = 3e6; s.crystals = 5000; s.energy = 30; s.seen = ['hub','chars','gear','jewel','shop','runes']; localStorage.setItem('mw-profile-v1', JSON.stringify(s)); });
await p.reload(); await p.waitForTimeout(400);
await shot('01-hub-full');
await click('.tab:nth-child(2)'); await p.waitForTimeout(300);
await click('[data-a="stop3"]');
await click('[data-a="auto"]'); await p.waitForTimeout(2600); await shot('02-auto');
await p.waitForTimeout(9000); await click('[data-a="auto"]'); await p.waitForTimeout(300); await shot('03-auto-summary');
await p.evaluate(() => document.querySelector('.rewardov')?.click());
await click('[data-a="synth"]'); await p.waitForTimeout(200);
await p.evaluate(() => document.querySelectorAll('[data-a="synGem"]')[5]?.click()); await p.waitForTimeout(100);
await p.evaluate(() => { const g = document.querySelectorAll('[data-a="synGem"]'); g[0]?.click(); g[1]?.click(); g[2]?.click(); });
await p.waitForTimeout(100); await click('[data-a="synEss"][data-v="small"]'); await p.waitForTimeout(200);
await shot('04-synth');
await click('[data-a="synGo"]'); await p.waitForTimeout(400); await shot('05-synth-done');
await p.evaluate(() => { const s = JSON.parse(localStorage.getItem('mw-profile-v1')); s.energy = 55; localStorage.setItem('mw-profile-v1', JSON.stringify(s)); });
await click('.tab:nth-child(1)'); await p.waitForTimeout(200);
await click('[data-a="chest"][data-v="runes:10"]'); await p.waitForTimeout(300); await p.evaluate(() => document.querySelector('.rewardov')?.click());
await p.evaluate(() => { document.querySelector('#view').scrollTop = 520; }); await p.waitForTimeout(200); await shot('06-shop');
await click('.tab:nth-child(4)'); await click('[data-a="sub"][data-v="runes"]'); await p.waitForTimeout(400); await shot('07-runes');
await click('[data-a="sub"][data-v="chars"]'); await p.waitForTimeout(400); await shot('08-chars');
await p.reload(); await p.waitForTimeout(400); await shot('09-hub-over');
console.log(errs);
await b.close();
