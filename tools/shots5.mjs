// Screenshots: hero screen (characters / gear / runes), item popup, shop tabs, lottery.
import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 820 }, deviceScaleFactor: 2, hasTouch: true });
const errs = []; p.on('pageerror', e => errs.push(String(e)));
const shot = n => p.screenshot({ path: `shots/r-${n}.png` });
const js = f => p.evaluate(f);
await p.goto('file://' + process.cwd() + '/dist/index.html');
await js(() => localStorage.clear()); await p.reload();
await p.click('[data-v="veles"]'); await p.click('[data-a="startGo"]');
await js(() => { const s = JSON.parse(localStorage.getItem('mw-profile-v1')); s.crystals = 30000; s.gold = 2e6; s.scrolls = 3000; s.heroes.perun.particles = 60; s.heroes.hades.particles = 12; s.seen = ['hub','heroes','gear','jewel','shop','runes','lottery']; localStorage.setItem('mw-profile-v1', JSON.stringify(s)); });
await p.reload(); await p.waitForTimeout(200);
await p.click('.tab >> nth=0'); await shot('1-shop-chests');
await js(() => document.querySelector('[data-a="chest"][data-v="set:10"]').click());
await js(() => document.querySelector('[data-a="chest"][data-v="obsidian:10"]').click());
await js(() => document.querySelector('[data-a="chest"][data-v="silver:10"]').click());
await js(() => document.querySelector('[data-a="shopTab"][data-v="daily"]').click()); await shot('2-shop-daily');
await p.click('.tab >> nth=3'); await shot('3-gear');
await js(() => document.querySelector('[data-a="smith"]').click()); await p.waitForTimeout(100);
await js(() => document.querySelector('.icard').click()); await p.waitForTimeout(100); await shot('4-item');
await js(() => document.querySelector('[data-a="equip"]').click()); await js(() => document.querySelector('[data-a="up"][data-v="10"]').click());
await js(() => document.querySelector('.x').click());
for (let i = 0; i < 3; i++) await js(() => document.querySelector('.icard')?.click()) , await js(() => document.querySelector('[data-a="equip"]')?.click()), await js(() => document.querySelector('.x')?.click());
await shot('5-gear-equipped');
await p.click('.tab >> nth=4'); await shot('6-chars');
await js(() => document.querySelector('[data-v="perun"][data-a="heroView"]').click()); await shot('7-chars-perun');
await js(() => document.querySelector('[data-a="go"][data-v="runes"]').click()); await shot('8-runes');
await js(() => document.querySelector('.setbtn.lot').click()); await js(() => document.querySelector('[data-a="spin"][data-v="1"]').click()); await p.waitForTimeout(1700); await shot('9-lottery');
console.log(errs);
await b.close();
