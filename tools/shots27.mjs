import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 800 }, deviceScaleFactor: 2, hasTouch: true });
const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
const shot = n => p.screenshot({ path: `shots/w3-${n}.png` });
const click = sel => p.evaluate(s => document.querySelector(s)?.click(), sel);
await p.goto('file://' + process.cwd() + '/dist/index.html'); await p.waitForTimeout(3400);
await click('[data-a="startPick"][data-v="hydra"]'); await click('[data-a="startGo"]'); await p.waitForTimeout(300);
await p.evaluate(() => {
  const s = JSON.parse(localStorage.getItem('mw-profile-v1'));
  s.seen = ['hub','chars','gear','jewel','shop','runes','settings']; s.crystals = 90000; s.gold = 9e6; s.shards = 5000; s.couponsSmall = 3; s.couponsBig = 4;
  localStorage.setItem('mw-profile-v1', JSON.stringify(s));
});
await p.reload(); await p.waitForTimeout(3600);
await click('[data-a="go"][data-v="shop"]'); await p.waitForTimeout(300);
await p.evaluate(() => document.querySelector('.tavern')?.scrollIntoView()); await p.waitForTimeout(200); await shot('01-tavern');
await click('[data-a="hsearch"][data-v="small:1"]'); await p.waitForTimeout(450); await shot('02-one-mid');
await p.waitForTimeout(1300); await shot('03-one');
await click('.rewardov .rwin'); await p.waitForTimeout(200);
await click('[data-a="hsearch"][data-v="big:10"]'); await p.waitForTimeout(1500); await shot('04-reveal');
for (let i = 0; i < 6 && await p.evaluate(() => !!document.querySelector('.rewardov.reveal')); i++) await click('.rewardov.reveal');
await p.waitForTimeout(1800); await shot('05-grid10');
await click('.rewardov [data-a="hsearch"][data-v="big:1"]'); await p.waitForTimeout(400);
for (let i = 0; i < 6 && await p.evaluate(() => !!document.querySelector('.rewardov.reveal')); i++) await click('.rewardov.reveal');
await p.waitForTimeout(1600); await shot('06-again1');
await click('.rewardov'); await p.waitForTimeout(200);
await click('[data-a="chest"][data-v="obsidian:1"]'); await p.waitForTimeout(1600); await shot('07-chest1');
await click('.rewardov'); await click('[data-a="chest"][data-v="runes:1"]'); await p.waitForTimeout(1600); await shot('08-runechest');
await click('.rewardov'); await click('[data-a="chest"][data-v="set:10"]'); await p.waitForTimeout(2200); await shot('09-set10');
console.log(JSON.stringify(errs)); await b.close();
