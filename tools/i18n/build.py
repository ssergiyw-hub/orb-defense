# правка 121: tools/i18n/keys.json + tools/i18n/tr*.tsv  ->  src/i18n/dict.ts
# row in tools/i18n/src/tr*.txt: N|uk|en|de|es|pt|pl|tr|fr|it   ({} in order, or {0} {1}… by number)
import json, glob, re, sys
LANGS = ['uk', 'en', 'de', 'es', 'pt', 'pl', 'tr', 'fr', 'it']
keys = json.load(open('tools/i18n/keys.json', encoding='utf8'))
tr = {l: [''] * len(keys) for l in LANGS}
errs = 0
for f in sorted(glob.glob('tools/i18n/src/tr*.txt')):
    for ln, row in enumerate(open(f, encoding='utf8').read().split('\n'), 1):
        if not row.strip(): continue
        cols = row.split('|')
        if len(cols) != 10: print(f'{f}:{ln}: {len(cols)} columns'); errs += 1; continue
        n = int(cols[0]); k = keys[n]
        for l, v in zip(LANGS, cols[1:]):
            v = v.strip()
            ph = len(re.findall(r'\{\d*\}', v)); idx = sorted(int(x) for x in re.findall(r'\{(\d+)\}', v))
            if idx and idx != list(range(k.count('{}'))): print(f'{f}:{ln} #{n} {l}: indexes {idx}'); errs += 1; continue
            if ph != k.count('{}'): print(f'{f}:{ln} #{n} {l}: placeholders {v.count("{}")} != {k.count("{}")}: {k} -> {v}'); errs += 1; continue
            tr[l][n] = v
if '--identity' in sys.argv:  # coverage check: every key 'translates' to itself
    tr = {l: list(keys) for l in LANGS}
miss = {l: sum(1 for v in tr[l] if not v) for l in LANGS}
print('missing per language:', miss, 'errors:', errs)
with open('src/i18n/dict.ts', 'w', encoding='utf8') as o:
    o.write('// generated by tools/i18n/build.py — do not edit by hand (правка 121)\n')
    o.write('export const KEYS: string[] = ' + json.dumps(keys, ensure_ascii=False) + ';\n')
    o.write('export const TR: Record<string, string[]> = ' + json.dumps(tr, ensure_ascii=False) + ';\n')
